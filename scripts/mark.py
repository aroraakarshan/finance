"""Daily mark to market of every position, with alerts and the allocation check.

trading/positions.csv holds one row per holding in every account plus the paper trades of
journal/trades.csv. Each run syncs it with the broker readers: qty, cost, currency, market, status
and source are refreshed; a new holding gets a row (default label and asset, sell_if "to set",
review in 91 days); a holding no longer held keeps its row with qty 0 and status closed. label,
asset, thesis, sell_if, stop, target and review are hand-written and never overwritten (ticker and
name only when blank). US cost_inr = cost x USD/INR of the day the cost last changed.

Prices: US stocks and NSE stocks/ETFs (<SYMBOL>.NS) from scripts.value.closes (yfinance, cached,
offline fallback); mutual funds from the AMFI NAV file (scripts.value.navs, cached the same way);
HDFC savings, FDs (principal + accrued), broker cash, physical gold and the hand-entered rows of
portfolio/manual-assets.csv (EPF, Punjab Gramin Bank) as scripts.value.snapshot values them.
Day change = last close vs the close before (price cache), else vs the newest earlier
marks file.

Writes trading/marks/<date>.csv, trading/marks/README.md, trading/alerts.md and the generated
section of portfolio/targets.md. Alerts: stop or target hit, day move over 7% (for information only
when under Rs 1,000), news score -2
(news/<SYMBOL>.md), results within 5 trading days (news catalysts), allocation outside its band
(portfolio/targets.md; "info" when the row names a fix in progress; the plan's global funds split into US and
non-US by FUND_US, REITs their own class), FD maturity within 30 days, HDFC savings + emergency Kotak
Arbitrage (holdings counted up to Rs 4 L) below the Rs 6 L emergency fund (info only until Kotak Arbitrage is held).
Exit code 1 when an alert needs action.

Run: python -m scripts.mark [--offline]
"""
