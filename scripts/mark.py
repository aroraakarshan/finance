def holdings(s: dict, old: pd.DataFrame, offline: bool) -> tuple[list[dict], list[str]]:
    """Current holdings of every account as rows (COLS subset plus price, price_date, maturity for rows valued
    here). s = value.snapshot()."""
    rows, notes, fx = [], [], s["fx"]
    us = s["holdings"][s["holdings"].market == "US"]
    for r in us.itertuples():
        asset = FUND_ASSET if r.symbol in FUND_US else ASSET_BY_SYMBOL.get(r.symbol, "US equity")
        rows.append(dict(symbol=r.symbol, name=news_name(r.symbol), market="US", account=r.account, asset=asset,
                         ticker=r.symbol, qty=r.qty, currency="USD", cost_native=r.cost, source=f"{r.account} reader"))
    try:
        eq, day = angelone.open_holdings()
        for r in eq.itertuples():
            name = news_name(r.symbol)
            asset = "Silver" if "SILVER" in r.symbol else "Gold" if "GOLD" in r.symbol else \
                "REIT" if is_reit(r.symbol, name) else "India equity"
            rows.append(dict(symbol=r.symbol, name=name, market="India", account="AngelOne",
                             asset=asset, ticker=f"{r.symbol}.NS", qty=r.qty, currency="INR", cost_native=r.cost,
                             source=f"AngelOne TaxPnL open holdings {day:%Y-%m-%d}"))
    except (Exception, SystemExit) as e:
        notes.append(f"AngelOne stocks not read: {e}")
    try:
        mf, mday = angelone.mutual_funds(), angelone.file_date(angelone.MF_FILE)
        mf = mf.rename(columns={"Fund Name": "fund", "Invested Value": "invested", "Market Value": "value"})
        known = {n.casefold(): (sym, t) for n, sym, t in zip(old.name, old.symbol, old.ticker)
                 if isinstance(t, str) and t.startswith("AMFI:")}
        table = None
        for r in mf.itertuples():
            sym, ticker = known.get(r.fund.casefold(), (None, None))
            if sym is None:
                if table is None and not offline:
                    table = value.amfi()
                code = amfi_code(table, r.fund, r.value / r.Units) if table is not None else None
                sym, ticker = (f"MF-{code}", f"AMFI:{code}") if code else (re.sub(r"\W+", "-", r.fund)[:24], "")
            rows.append(dict(symbol=sym, name=r.fund, market="India", account="AngelOne MF", asset=fund_asset(r.fund),
                             ticker=ticker, qty=r.Units, currency="INR", cost_native=r.invested,
                             price=r.value / r.Units, price_date=mday, source=f"AngelOne MF holdings {mday:%Y-%m-%d}"))
    except (Exception, SystemExit) as e:
        notes.append(f"AngelOne mutual funds not read: {e}")
    acc = s["accounts"]
    for name, account in (("INDmoney cash", "INDmoney"), ("IBKR cash", "IBKR")):
        a = acc[acc.name == name]
        if len(a):
            rows.append(dict(symbol="USD-CASH", name=name, market="US", account=account, asset="Cash (USD)", ticker="",
                             qty=float(a.value.iloc[0]), currency="USD", cost_native=float(a.value.iloc[0]), price=1.0,
                             price_date=pd.Timestamp(a.as_of.iloc[0]), source=a.source.iloc[0]))
    bal, sday, last4 = s["savings"]
    rows.append(dict(symbol="HDFC-SAVINGS", name=f"HDFC savings ****{last4}", market="India", account="HDFC",
                     asset="Cash", ticker="", qty=bal, currency="INR", cost_native=bal, price=1.0, price_date=sday,
                     source=f"HDFC savings CSV to {sday:%Y-%m-%d}"))
    today = pd.Timestamp.today().normalize()
    for r in s["fds"].itertuples():
        rows.append(dict(symbol=f"FD-{r.fd}", name=f"HDFC FD ****{r.fd}, {r.rate:g}% to {r.maturity:%Y-%m-%d}",
                         market="India", account="HDFC FD", asset="FD", ticker="", qty=1.0, currency="INR",
                         cost_native=r.principal, price=r.value, price_date=today, maturity=r.maturity,
                         source=f"HDFC FD summary {r.as_of:%Y-%m-%d}; accrued to today"))
    g = s["gold"]
    _, gday, gsrc = s["gold_rate"]
    rows.append(dict(symbol="GOLD-PHYSICAL", name=f"Physical gold ({g.grams.sum():.1f} g net)", market="India",
                     account="Physical", asset="Gold", ticker="", qty=g.grams.sum(), currency="INR",
                     cost_native=g.paid.sum(), price=g.value_now.sum() / g.grams.sum(), price_date=gday,
                     source=f"gold invoices x {gsrc}"))
    for r in s.get("manual", pd.DataFrame()).itertuples():
        rows.append(dict(symbol=r.symbol, name=r.name, market="India", account=r.account, asset=r.asset, ticker="",
                         qty=1.0, currency="INR", cost_native=r.value, price=r.value,
                         price_date=pd.Timestamp(r.as_of), source=f"portfolio/manual-assets.csv: {r.source}"))
    rows += paper_trades(notes)
    for r in rows:
        r.setdefault("status", "open")
        r["cost_inr"] = r["cost_native"] * (fx if r["currency"] == "USD" else 1) if r["currency"] in ("USD", "INR") \
            else float("nan")
    return rows, notes


def amfi_code(table: pd.DataFrame, name: str, nav: float) -> str | None:
    """AMFI scheme code of a fund name (direct plan, growth), checked against the export's NAV (within 5%)."""
    t = table[(table.name.str.casefold() == name.casefold()) & table.plan.str.contains("Direct", case=False)
              & table.option.str.contains("Growth", case=False)]
    t = t[(t.nav / nav - 1).abs() < 0.05]
    return t.code.iloc[0] if len(t) == 1 else None


def paper_trades(notes: list[str]) -> list[dict]:
    if not TRADES.exists():
        return []
    t = pd.read_csv(TRADES, dtype=str).fillna("")
    out = []
    for r in t[t.paper_or_real.str.lower() == "paper"].itertuples():
        india = "india" in r.market.lower()
        cur = "INR" if india else "USD" if "us" in r.market.lower() else ""
        if not cur:
            notes.append(f"paper {r.symbol}: market {r.market!r} has no FX here; not valued in INR")
        try:
            qty, price = float(r.qty), float(r.price)
        except ValueError:
            notes.append(f"paper {r.symbol} {r.date}: qty or price not a number")
            continue
        sign = -1 if r.side.upper().startswith("S") else 1
        out.append(dict(symbol=r.symbol, name=news_name(r.symbol), market=r.market, account="paper", asset="Trade",
                        ticker=f"{r.symbol}.NS" if india else r.symbol, qty=sign * qty, currency=cur,
                        cost_native=sign * qty * price, stop=r.stop_loss, target=r.target, thesis=r.plan,
                        status="closed" if r.exit_date else "paper", source=f"journal/trades.csv {r.date}"))
    return out


# ---------- positions.csv ----------

def load_positions() -> pd.DataFrame:
    if POSITIONS.exists():
        return pd.read_csv(POSITIONS, dtype=str, keep_default_na=False)
    return pd.DataFrame(columns=COLS)


def sync(old: pd.DataFrame, rows: list[dict]) -> tuple[pd.DataFrame, list[str]]:
    """New positions table: readers' facts refreshed, hand columns kept."""
    notes, out, seen = [], [], set()
    review = f"{date.today() + pd.Timedelta(days=91):%Y-%m-%d}"
    idx = {(a, s): i for i, (a, s) in enumerate(zip(old.account, old.symbol))}
    for r in rows:
        key = (r["account"], r["symbol"])
        seen.add(key)
        if key in idx:
            o = old.iloc[idx[key]].to_dict()
            changed = o["qty"] != qty_text(r["qty"]) or o["cost_native"] != f"{r['cost_native']:.2f}"
            new = {**o, **{k: r[k] for k in ("market", "currency", "status", "source")}}
            new["qty"], new["cost_native"] = qty_text(r["qty"]), f"{r['cost_native']:.2f}"
            if changed or not o["cost_inr"]:
                new["cost_inr"] = f"{r['cost_inr']:.0f}" if r["cost_inr"] == r["cost_inr"] else ""
            for k in ("name", "ticker"):
                new[k] = new[k] or r.get(k, "")
        else:
            new = {k: "" for k in COLS} | {k: v for k, v in r.items() if k in COLS}
            new["qty"], new["cost_native"] = qty_text(r["qty"]), f"{r['cost_native']:.2f}"
            new["cost_inr"] = f"{r['cost_inr']:.0f}" if r["cost_inr"] == r["cost_inr"] else ""
            new["label"] = default_label(r["asset"], r["account"], r.get("ticker", ""))
            new["sell_if"], new["review"] = r.get("sell_if") or "to set", review
            notes.append(f"new position {r['account']} {r['symbol']} (label {new['label']}; set sell_if)")
        out.append(new)
    for o in old.itertuples(index=False):
        if (o.account, o.symbol) not in seen:
            d = o._asdict()
            if d["status"] != "closed":
                notes.append(f"{o.account} {o.symbol} no longer held: marked closed")
            d["status"], d["qty"] = "closed", "0"
            out.append(d)
    p = pd.DataFrame(out, columns=COLS).fillna("")
    order = {k: i for i, k in enumerate(["open", "paper", "closed"])}
    p = p.sort_values(["status", "account", "symbol"], key=lambda c: c.map(order) if c.name == "status" else c)
    return p.reset_index(drop=True), notes


def qty_text(x: float) -> str:
    return f"{x:.6f}".rstrip("0").rstrip(".")


def fnum(x) -> float:
    try:
        return float(str(x).replace(",", "").replace("$", "").replace("Rs", ""))
    except ValueError:
        return float("nan")


