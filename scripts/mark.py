def lakh(x: float) -> str:
    return "-" if pd.isna(x) else (f"Rs {x / 1e7:.2f} Cr" if abs(x) >= 1e7 else f"Rs {x / 1e5:.2f} L")


def news_name(symbol: str) -> str:
    f = NEWS / f"{symbol}.md"
    if f.exists():
        m = re.match(r"# *\S+ *- *(.+)", f.read_text().splitlines()[0])
        if m:
            return re.sub(r"\s*\(.*\)$", "", m[1]).strip()
    return symbol


def is_reit(symbol: str, name: str) -> bool:
    return symbol in REITS or "REIT" in symbol or bool(re.search(r"\bREIT\b|Real Estate Investment Trust", name, re.I))


def fund_asset(name: str) -> str:
    n = name.lower()
    if is_reit("", name):
        return "REIT"
    if "arbitrage" in n:
        return "Arbitrage"
    if "liquid" in n or "overnight" in n:
        return "Cash"
    if "silver" in n:
        return "Silver"
    if "gold" in n:
        return "Gold"
    return "India equity"


def default_label(asset: str, account: str, ticker: str) -> str:
    if account == "paper":
        return "trade"
    if asset in ("Cash", "Cash (USD)", "FD", "Arbitrage", "EPF"):
        return "cash"
    if asset == "Gold":
        return "gold"
    if asset in ("World ex-US", "Non-US equity", FUND_ASSET) or str(ticker).startswith("AMFI:"):
        return "core"
    return "satellite"


