def news_score(symbol: str) -> int | None:
    f = NEWS / f"{symbol}.md"
    if not f.exists():
        return None
    m = re.search(r"^Score:\s*([+-]?\d)", f.read_text(), re.M)
    return int(m[1]) if m else None


def results_dates(symbol: str) -> list[tuple[str, str]]:
    """(date, event) of results rows with an exact date in the Catalysts table of news/<symbol>.md."""
    f = NEWS / f"{symbol}.md"
    if not f.exists():
        return []
    m = re.search(r"^## Catalysts\n(.*?)(?=^## |\Z)", f.read_text(), re.S | re.M)
    out = []
    for line in (m[1] if m else "").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        d = re.match(r"(\d{4}-\d{2}-\d{2})", cells[0]) if line.startswith("|") and len(cells) > 1 else None
        if d and re.search(r"result|earnings", cells[1], re.I):
            out.append((d[1], cells[1]))
    return out


def alerts(m: pd.DataFrame, p: pd.DataFrame, alloc: list[dict], today: str) -> list[dict]:
    out = []

    def add(level, kind, symbol, text, source):
        out.append(dict(level=level, kind=kind, symbol=symbol, text=text, source=source))

    sell_if = {(a, s): x for a, s, x in zip(p.account, p.symbol, p.sell_if)}
    live = m[m.status.isin(["open", "paper"])]
    for r in live.itertuples():
        money = f"{r.price:,.2f} {r.currency}"
        why = sell_if.get((r.account, r.symbol), "")
        if r.stop == r.stop and r.price <= r.stop:
            add("action", "stop hit", r.symbol, f"{r.name} ({r.account}) at {money} is at or below its stop "
                f"{r.stop:,.2f}: sell, or write a new stop in positions.csv. Sell if: {why}", "positions.csv")
        if r.target == r.target and r.price >= r.target:
            add("action", "target hit", r.symbol, f"{r.name} ({r.account}) at {money} reached its target "
                f"{r.target:,.2f}: take profit or raise the target. Sell if: {why}", "positions.csv")
        if r.day_change_pct == r.day_change_pct and abs(r.day_change_pct) > MOVE:
            level = "action" if abs(r.day_pnl_inr) >= MOVE_MIN_INR else "info"
            add(level, "big move", r.symbol, f"{r.name} ({r.account}) moved {r.day_change_pct:+.1%} on "
                f"{r.price_date} ({rs(r.day_pnl_inr)}): read the news before the next session.", "price cache")
    plan = {s: x for s, x, st in zip(p.symbol, p.sell_if, p.status) if st != "closed"}
    for sym in dict.fromkeys(live[~live.symbol.str.contains("-")].symbol):
        why = f" Sell if: {plan[sym]}." if plan.get(sym) else ""
        sc = news_score(sym)
        if sc is not None and sc <= -2:
            add("action", "news -2", sym, f"{sym}: news score {sc}: read news/{sym}.md and decide whether to "
                f"keep it.{why}", f"news/{sym}.md")
        for d, _ in results_dates(sym):
            days = int(np.busday_count(today, d))
            if 0 <= days <= RESULTS_DAYS:
                when = f"{days} trading day{'s' if days != 1 else ''}"
                add("action", "results soon", sym, f"{sym}: results on {d} ({when}): decide before then whether "
                    f"to hold through them.{why}", f"news/{sym}.md")
    for a in alloc:
        if a["state"] in ("below", "above"):
            fix = a.get("fix in progress", "")
            add("info" if fix else "action", "allocation", a["class"],
                f"{a['class']} is {a['pct']:.1f}% ({rs(a['current'])}), {a['state']} its band {a['band']}"
                + (f"; being fixed: {fix}" if fix else ": rebalance or change the band in portfolio/targets.md"),
                "portfolio/targets.md")
    for day, g in live[live.maturity != ""].groupby("maturity"):
        days = (pd.Timestamp(day) - pd.Timestamp(today)).days
        if 0 <= days <= FD_DAYS:
            add("action", "FD maturity", ", ".join(g.symbol), f"{len(g)} FD{'s' if len(g) > 1 else ''} "
                f"({rs(g.value_inr.sum())} today) mature on {day}, in {days} days: decide where the money goes "
                f"(portfolio/plan.md section 4).", "HDFC FD summary")
    own = m[m.status == "open"]
    sav = own[own.symbol == "HDFC-SAVINGS"].value_inr.sum()
    arb = own[own.name.str.contains(r"kotak arbitrage", case=False)]
    arb_em = min(arb.value_inr.sum(), EMERGENCY_ARB_CAP)
    total = sav + arb_em
    text = (f"HDFC savings {rs(sav)} + Kotak Arbitrage counted as emergency {rs(arb_em)} (holdings "
            f"{rs(arb.value_inr.sum())}, counted up to {rs(EMERGENCY_ARB_CAP)}) = {rs(total)}; emergency fund "
            f"floor {rs(EMERGENCY_INR)}")
    if arb.empty:
        add("info", "emergency fund", "HDFC-SAVINGS", text + " (Kotak Arbitrage not held yet; alert starts once it "
            "is).", "positions.csv")
    elif total < EMERGENCY_INR:
        add("action", "emergency fund", "HDFC-SAVINGS", text + ": below the floor, top up savings or the "
            "emergency Kotak Arbitrage (portfolio/plan.md).", "positions.csv")
    return out


# ---------- notes ----------

def table(header: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|",
            *("| " + " | ".join(str(c) for c in r) + " |" for r in rows)]


def qty_shown(x: float) -> str:
    return f"{x:,.0f}" if abs(x) >= 1000 else f"{x:,.4f}".rstrip("0").rstrip(".")


def pct(x: float) -> str:
    return "-" if pd.isna(x) else f"{x:+.1%}"


def write_alerts(al: list[dict], today: str, notes: list[str]) -> None:
    act = [a for a in al if a["level"] == "action"]
    info = [a for a in al if a["level"] == "info"]
    summary = [f"{len(act)} action{'s' if len(act) != 1 else ''} needed today ({today})." if act
               else f"No action needed today ({today})."]
    summary += [f"- {a['text']}" for a in act[:3]]
    if len(act) > 3:
        summary.append(f"- and {len(act) - 3} more in Actions below.")
    elif info:
        summary.append(f"{len(info)} for information (allocation being fixed by the plan, data notes) below.")
    lines = ["# Alerts", "", "## Summary", *summary, "",
             f"Written by `python -m scripts.mark` on {today} from [positions](positions.csv), "
             f"[marks](marks/README.md), news files and [targets](../portfolio/targets.md). "
             f"Agents never place orders; you decide and trade.", "", "## Actions"]
    lines += table(["What", "Holding", "Detail", "Source"], [[a["kind"], a["symbol"], a["text"], a["source"]]
                                                           for a in act]) if act else ["None."]
    lines += ["", "## For information"]
    lines += table(["What", "Holding", "Detail", "Source"], [[a["kind"], a["symbol"], a["text"], a["source"]]
                                                           for a in info]) if info else ["None."]
    lines += ["", "## Data notes"] + ([f"- {n}" for n in notes] or ["None."])
    ALERTS.write_text("\n".join(lines) + "\n")


def write_readme(m: pd.DataFrame, al: list[dict], today: str, total: float) -> None:
    own = m[m.status == "open"]
    priced = own[own.day_pnl_inr.notna()]
    day = priced.day_pnl_inr.sum()
    base = (priced.value_inr - priced.day_pnl_inr).sum()
    days = sorted({d for d in priced.price_date if d})
    movers = priced.loc[priced.day_pnl_inr.abs().sort_values(ascending=False).index].head(8)
    near = m[m.status.isin(["open", "paper"]) & ((m.to_stop_pct.abs() <= NEAR) | (m.to_target_pct.abs() <= NEAR))]
    nstop = int((m[m.status.isin(["open", "paper"])].stop.notna()).sum())
    act = sum(a["level"] == "action" for a in al)
    top = ", ".join(f"{r.symbol} {pct(r.day_change_pct)} ({rs(r.day_pnl_inr)})" for r in movers.head(3).itertuples())
    lines = ["# Daily marks", "", "## Summary",
             f"Marked {today}: your holdings {rs(total)} ({lakh(total)}); change on the last trading day "
             f"({', '.join(days[-1:]) or '-'}) {rs(day)} ({day / base:+.2%})." if base else
             f"Marked {today}: your holdings {rs(total)}; no day change (no earlier price).",
             f"Biggest movers: {top or '-'}.",
             f"Near stop or target (within {NEAR:.0%}): " + (", ".join(near.symbol) if len(near) else
                                                             f"none ({nstop} positions have a stop set)."),
             f"Alerts: {act} action(s) today, see [alerts.md](../alerts.md).", "",
             f"Written by `python -m scripts.mark` (also run by `scripts.update`). One file per day: "
             f"[{today}.csv]({today}.csv). Day change: last close vs the close before (USD holdings at today's "
             f"USD/INR); MF NAVs from AMFI; FDs, savings and gold as in [summary](../../portfolio/summary.md).", "",
             "## Biggest movers"]
    lines += table(["Holding", "Account", "Price", "Day", "Day in INR", "Value"],
                   [[f"{r.symbol} ({r.name})" if r.name != r.symbol else r.symbol, r.account,
                     f"{r.price:,.2f} {r.currency}", pct(r.day_change_pct), rs(r.day_pnl_inr), rs(r.value_inr)]
                    for r in movers.itertuples()])
    lines += ["", "## Near stop or target"]
    lines += table(["Holding", "Account", "Price", "Stop", "Target", "To stop", "To target"],
                   [[r.symbol, r.account, f"{r.price:,.2f}", f"{r.stop:,.2f}" if r.stop == r.stop else "-",
                     f"{r.target:,.2f}" if r.target == r.target else "-", pct(r.to_stop_pct), pct(r.to_target_pct)]
                    for r in near.itertuples()]) if len(near) else ["None."]
    lines += ["", "## By label"]
    g = own.groupby("label").agg(n=("symbol", "size"), value=("value_inr", "sum"), cost=("cost_inr", "sum"),
                                 day=("day_pnl_inr", "sum"))
    paper = m[m.status == "paper"]
    lines += table(["Label", "Positions", "Value", "Share", "Gain on cost", "Day"],
                   [[k, int(r.n), rs(r.value), f"{r.value / total:.1%}", rs(r.value - r.cost), rs(r.day)]
                    for k, r in g.sort_values("value", ascending=False).iterrows()]
                   + ([["trade (paper)", len(paper), rs(paper.value_inr.sum()), "-",
                        rs(paper.pnl_inr.sum()), rs(paper.day_pnl_inr.sum())]] if len(paper) else []))
    lines += ["", "## Positions"]
    lines += table(["Holding", "Account", "Label", "Qty", "Price", "Of", "Value", "Gain on cost", "Day"],
                   [[r.symbol if r.name == r.symbol else f"{r.symbol} ({r.name})", r.account, r.label,
                     qty_shown(r.qty), f"{r.price:,.2f} {r.currency}", r.price_date, rs(r.value_inr),
                     f"{rs(r.pnl_inr)} ({pct(r.pnl_pct)})", pct(r.day_change_pct)]
                    for r in m.sort_values("value_inr", ascending=False).itertuples()])
    files = sorted(MARKS.glob("20??-??-??.csv"))[-10:]
    lines += ["", "## Earlier days", ", ".join(f"[{f.stem}]({f.name})" for f in reversed(files)) or "-"]
    (MARKS / "README.md").write_text("\n".join(lines) + "\n")


# ---------- run ----------

def run(s: dict | None = None, offline: bool = False) -> dict:
    """Sync positions, mark, write the files. s: a value.snapshot() result (made here when None).
    Returns {total, alerts, notes, positions, marks}."""
    today = f"{date.today():%Y-%m-%d}"
    notes = []
    if s is None:
        s = value.snapshot(offline)
        notes += [n for n in s["notes"] if not n.startswith("AngelOne left out")]
    old = load_positions()
    rows, n = holdings(s, old, offline)
    notes += n
    p, n = sync(old, rows)
    notes += n
    POSITIONS.parent.mkdir(parents=True, exist_ok=True)
    p.to_csv(POSITIONS, index=False)
    m, n = mark(p, rows, s, offline, today)
    notes += n
    MARKS.mkdir(parents=True, exist_ok=True)
    m.to_csv(MARKS / f"{today}.csv", index=False, float_format="%.6g")
    alloc, total = allocation(m, read_targets())
    write_targets(alloc, total, m, today)
    al = alerts(m, p, alloc, today)
    write_alerts(al, today, notes)
    write_readme(m, al, today, total)
    return {"total": total, "alerts": al, "notes": notes, "positions": p, "marks": m}


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--offline", action="store_true", help="cached prices and NAVs only (no network)")
    args = ap.parse_args()
    r = run(offline=args.offline)
