def previous_marks(today: str) -> pd.DataFrame | None:
    files = sorted(f for f in MARKS.glob("20??-??-??.csv") if f.stem < today)
    return pd.read_csv(files[-1]) if files else None


def mark(p: pd.DataFrame, rows: list[dict], s: dict, offline: bool, today: str) -> tuple[pd.DataFrame, list[str]]:
    notes, fx = [], s["fx"]
    live = p[p.status != "closed"].copy()
    own = {(r["account"], r["symbol"]): r for r in rows}
    yf = sorted({t for t in live.ticker if t and not t.startswith("AMFI:")})
    amfi = sorted({t[5:] for t in live.ticker if t.startswith("AMFI:")})
    px, n = value.closes(yf, offline) if yf else ({}, [])
    notes += n
    nav, n = value.navs(amfi, offline)
    notes += n
    px.update(nav)
    cache, prevfile = value.cached_prices(), previous_marks(today)
    out = []
    for r in live.itertuples(index=False):
        o = own.get((r.account, r.symbol), {})
        if r.ticker in px:
            price, pday = px[r.ticker]
        elif "price" in o:
            price, pday = o["price"], o["price_date"]
            if r.ticker:
                notes.append(f"{r.account} {r.symbol}: no {r.ticker} price; reader value of {pday:%Y-%m-%d} used")
        else:
            price, pday = float("nan"), pd.NaT
            notes.append(f"{r.account} {r.symbol}: no price")
        prev = float("nan")
        c = cache.get(r.ticker, {})
        if "prev" in c and c["date"] == f"{pday:%Y-%m-%d}":
            prev = c["prev"]
        elif prevfile is not None and r.asset not in ("Cash", "Cash (USD)", "FD", "EPF"):
            m = prevfile[(prevfile.account == r.account) & (prevfile.symbol == r.symbol)]
            if len(m) and str(m.price_date.iloc[0]) < f"{pday:%Y-%m-%d}":
                prev = float(m.price.iloc[0])
        qty, rate = fnum(r.qty), fx if r.currency == "USD" else 1.0 if r.currency == "INR" else float("nan")
        val = qty * price
        cost = fnum(r.cost_inr)
        stop, target = fnum(r.stop), fnum(r.target)
        out.append(dict(date=today, symbol=r.symbol, name=r.name, account=r.account, label=r.label, asset=r.asset,
                        status=r.status, qty=qty, currency=r.currency, price=price,
                        price_date=f"{pday:%Y-%m-%d}" if pd.notna(pday) else "", prev_price=prev,
                        value_native=val, value_inr=val * rate, cost_inr=cost, pnl_inr=val * rate - cost,
                        pnl_pct=(val * rate / cost - 1) if cost else float("nan"),
                        day_change_pct=price / prev - 1 if prev else float("nan"),
                        day_pnl_inr=qty * (price - prev) * rate, stop=stop, target=target,
                        to_stop_pct=price / stop - 1 if stop else float("nan"),
                        to_target_pct=target / price - 1 if target else float("nan"),
                        maturity=f"{o['maturity']:%Y-%m-%d}" if "maturity" in o else ""))
    m = pd.DataFrame(out)
    stale = m[(m.price_date != "") & (pd.to_datetime(m.price_date, errors="coerce")
                                     < pd.Timestamp(today) - pd.Timedelta(days=STALE_DAYS))]
    if len(stale):
        notes.append(f"{len(stale)} prices older than {STALE_DAYS} days (oldest {stale.price_date.min()}): "
                     + ", ".join(dict.fromkeys(stale.symbol)))
    return m, notes


# ---------- targets ----------

def read_targets() -> list[dict]:
    """Rows of the hand-written table in portfolio/targets.md (before the generated section)."""
    if not TARGETS.exists():
        return []
    text = TARGETS.read_text().split(GEN_START)[0]
    rows, header = [], None
    for line in text.splitlines():
        if not line.startswith("|"):
            header = None
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = [c.lower() for c in cells]
            continue
        if set(cells[0]) <= set("-: "):
            continue
        if "counts" in header and "band" in header:
            rows.append(dict(zip(header, cells)))
    return rows


def band(text: str) -> tuple[float, float, str] | None:
    """'30-45%' -> (30, 45, '%'); 'Rs 5-10 L' -> (5e5, 10e5, 'Rs'); '-' -> None."""
    m = re.search(r"([\d.]+)\s*-\s*([\d.]+)\s*(%|L\b|Cr\b)", text)
    if not m:
        return None
    lo, hi, unit = float(m[1]), float(m[2]), m[3]
    k = {"%": 1, "L": 1e5, "Cr": 1e7}[unit]
    return lo * k, hi * k, "%" if unit == "%" else "Rs"


def look_through(own: pd.DataFrame) -> pd.DataFrame:
    """(symbol, asset, value_inr) with every FUND_US fund split into its "US equity" and "Non-US equity" parts
    (by symbol, whatever its asset); "World ex-US" positions count as "Non-US equity"."""
    out = []
    for r in own.itertuples():
        us = FUND_US.get(r.symbol)
        if us is None:
            out.append((r.symbol, "Non-US equity" if r.asset == "World ex-US" else r.asset, r.value_inr))
        else:
            out += [(r.symbol, "US equity", r.value_inr * us), (r.symbol, "Non-US equity", r.value_inr * (1 - us))]
    return pd.DataFrame(out, columns=["symbol", "asset", "value_inr"])


def allocation(m: pd.DataFrame, targets: list[dict]) -> tuple[list[dict], float]:
    own = m[(m.status == "open") & m.value_inr.notna()]
    total = own.value_inr.sum()
    expo = look_through(own)
    out = []
    for t in targets:
        counts = t["counts"]
        if "single stock" in counts.lower():
            st = own[own.asset.isin(["US equity", "India equity"]) & ~own.symbol.str.startswith("MF-")
                     & ~own.symbol.isin(list(FUND_US))]
            by = st.groupby("symbol").value_inr.sum().sort_values()
            cur, what = (by.iloc[-1], by.index[-1]) if len(by) else (0.0, "-")
        else:
            assets = [a.strip() for a in counts.split(",")]
            cur, what = expo[expo.asset.isin(assets)].value_inr.sum(), ""
        b = band(t["band"])
        if b is None:
            state = "not checked"
        else:
            x = cur / total * 100 if b[2] == "%" else cur
            state = "below" if x < b[0] else "above" if x > b[1] else "inside"
        out.append(dict(t, current=cur, pct=cur / total * 100 if total else float("nan"), state=state, what=what))
    return out, total


def write_targets(alloc: list[dict], total: float, m: pd.DataFrame, today: str) -> None:
    if not TARGETS.exists():
        return
    own = m[(m.status == "open") & m.value_inr.notna()]
    lines = [GEN_START, f"## Current ({today})", "",
             f"Written by `python -m scripts.mark` on {today}; total marked {rs(total)} ({lakh(total)}); "
             f"positions in [trading/positions.csv](../trading/positions.csv).", "",
             "| Class | Target | Band | Current | Share | State |", "|---|---|---|---|---|---|"]
    for a in alloc:
        cur = f"{rs(a['current'])}" + (f" ({a['what']})" if a["what"] else "")
        state = a["state"] + (" (fix in progress)" if a["state"] in ("below", "above") and a.get("fix in progress")
                              else "")
        lines.append(f"| {a['class']} | {a['target']} | {a['band']} | {cur} | {a['pct']:.1f}% | {state} |")
    lines += ["", "| Asset (positions.csv `asset`) | Value | Share |", "|---|---|---|"]
    for k, v in own.groupby("asset").value_inr.sum().sort_values(ascending=False).items():
        lines.append(f"| {k} | {rs(v)} | {v / total:.1%} |")
    lines.append(GEN_END)
    text = TARGETS.read_text()
    head = text.split(GEN_START)[0].rstrip()
    tail = text.split(GEN_END, 1)[1] if GEN_END in text else ""
    TARGETS.write_text(head + "\n\n" + "\n".join(lines) + tail.rstrip() + "\n")


